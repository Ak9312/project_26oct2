// Bundles src/ into api/_engine.js, the module the Vercel functions import.
// The src files share helpers as plain globals (no imports), so they are
// concatenated in dependency order and the public functions re-exported.
// Run: npm run generate
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { inlineSources } from './inline.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const ENGINE_FILES = ['text.js', 'parse.js', 'readability.js', 'keywords.js', 'llm.js', 'scoring.js', 'input.js', 'external.js', 'phrasecheck.js', 'appdata.js', 'pipeline.js'];
export const ENGINE_EXPORTS = [
  'normalizeInput', 'makeAuditId', 'runAudit', 'auditConfig', 'groqKeyProblem', 'buildReport', 'buildErrorReport',
  'readabilityTarget', 'summarize', 'upsertEntry', 'replaceEntry', 'listResponse', 'getResponse', 'reviewListResponse',
  'applyReview', 'applyValidation', 'validationResponse', 'toCsv',
];

const out = '// Generated by scripts/build-engine.mjs from src/ — do not edit. Run `npm run generate` after changing src/.\n' +
  inlineSources(ENGINE_FILES) + '\nexport { ' + ENGINE_EXPORTS.join(', ') + ' };\n';
writeFileSync(join(root, 'api', '_engine.js'), out);
console.log('wrote api/_engine.js (' + ENGINE_FILES.length + ' source files)');
